import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { png, drawing } from './png-fixtures.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const build = resolve(root, '../../build/image-spj');
mkdirSync(build, { recursive: true });
const temporary = mkdtempSync(join(build, 'tooling-'));
const source = join(temporary, 'source.png');
const encoded = png(64, 64, drawing());
writeFileSync(source, encoded);
function node(script, ...args) {
  const result = spawnSync(process.execPath, [join(root, script), ...args], { encoding: 'utf8', timeout: 30000 });
  if (result.error) throw result.error;
  return result;
}
const text = join(temporary, 'text.out'), binary = join(temporary, 'binary.out');
assert.equal(node('prepare-reference.mjs', source, text).status, 0);
const [header, ...body] = readFileSync(text, 'utf8').split('\n');
assert.equal(header, 'OJ_IMAGE_PNG_BASE64_V1');
assert.deepEqual(Buffer.from(body.join(''), 'base64'), encoded);
console.log('PASS text .out preserves PNG bytes');
assert.equal(node('prepare-reference.mjs', source, binary, 'binary').status, 0);
assert.deepEqual(readFileSync(binary), encoded);
console.log('PASS binary .out preserves PNG bytes');
assert.notEqual(node('prepare-reference.mjs', source, text).status, 0);
assert.deepEqual(Buffer.from(readFileSync(text, 'utf8').split('\n').slice(1).join(''), 'base64'), encoded);
console.log('PASS overwrite rejected without changing existing file');
const invalid = join(temporary, 'renamed-jpeg.png');
writeFileSync(invalid, Buffer.from([0xff, 0xd8, 0xff, 0xe0]));
assert.notEqual(node('prepare-reference.mjs', invalid, join(temporary, 'invalid.out')).status, 0);
console.log('PASS renamed non-PNG rejected');
assert.notEqual(node('prepare-reference.mjs', source, join(temporary, 'invalid-mode.out'), 'unknown').status, 0);
console.log('PASS invalid mode rejected');
const first = join(temporary, 'first.cpp'), second = join(temporary, 'second.cpp');
assert.equal(node('build.mjs', first).status, 0);
assert.equal(node('build.mjs', second).status, 0);
assert.deepEqual(readFileSync(first), readFileSync(second));
console.log('PASS deterministic single-file generation and vendor hashes');
const generated = readFileSync(first, 'utf8');
assert.ok(!generated.startsWith('\ufeff'));
assert.ok(!generated.includes('\r'));
assert.match(generated, /Copyright \(c\) 2005-2026 Lode Vandevenne/);
console.log('PASS UTF-8 without BOM, LF, dependency license retained');
assert.ok(!/^#include "(?:profile\.hpp|decoder_config\.hpp|\.\.\/vendor\/lodepng\/)/m.test(generated));
console.log('PASS project-local includes removed from generated source');
console.log('PASS 8 tooling checks (not native SPJ execution tests)');
