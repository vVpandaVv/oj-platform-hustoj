import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = dirname(fileURLToPath(import.meta.url));
const output = resolve(process.argv[2] ?? resolve(root, '../../build/image-spj/spj.cpp'));
const hashes = {
  'lodepng.h': '276479a13247c6ed324132f5bee5ad8d8b1f4c04077736f24f8d179ef71682fd',
  'lodepng.cpp': '3b88f84b56c78e4b50f533b84973ebfc50ec8d5978298088a00f7c7b1b3a06f8',
};
const read = (path) => readFileSync(resolve(root, path), 'utf8');
for (const [name, expected] of Object.entries(hashes)) {
  const bytes = readFileSync(resolve(root, 'vendor/lodepng', name));
  if (createHash('sha256').update(bytes).digest('hex') !== expected) throw Error(`Vendor hash mismatch: ${name}`);
}
const header = '// Generated by tools/image-spj/build.mjs. Edit source files, then regenerate.\n';
const implementation = read('vendor/lodepng/lodepng.cpp').replace(/^#include "lodepng\.h"\r?$/m,
  '// LodePNG header is embedded above; implementation otherwise unmodified.');
const main = read('src/image_spj.cpp').replace(/^#include "(?:profile\.hpp|decoder_config\.hpp|\.\.\/vendor\/lodepng\/lodepng\.(?:h|cpp))"\r?\n/gm, '');
const combined = [header, read('src/profile.hpp'), read('src/decoder_config.hpp'),
  read('vendor/lodepng/lodepng.h'), implementation, main].join('\n').replace(/\r\n/g, '\n');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, combined, 'utf8');
console.log(`Generated ${output} (${Buffer.byteLength(combined)} bytes)`);
