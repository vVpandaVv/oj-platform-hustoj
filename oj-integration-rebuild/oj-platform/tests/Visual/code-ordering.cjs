const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright');

(async () => {
  const root = path.resolve(__dirname, '../..');
  const visualOutput = path.resolve(root, '../../_notes/verification/2026-10-24/code-ordering-compact');
  fs.mkdirSync(visualOutput, {recursive:true});
  const fixture = JSON.parse(execFileSync(process.env.PHP_BINARY || 'D:/php/php.exe', ['tests/Support/render-code-ordering.php'], {cwd:root, encoding:'utf8'}));
  const teacher = '<form id="teacher"><input type="radio" name="code_entry_mode" value="full_code"><input type="radio" name="code_entry_mode" value="code_completion"><input type="radio" name="code_entry_mode" value="code_ordering" checked><fieldset><input type="checkbox" name="enabled_language_ids[]" value="0" checked><input type="checkbox" name="enabled_language_ids[]" value="1"><input type="checkbox" name="enabled_language_ids[]" value="3"><input type="checkbox" name="enabled_language_ids[]" value="6" checked></fieldset><div data-ojp-code-ordering><select name="ordering_language_key"><option value="python">Python</option><option value="c">C</option><option value="cpp">C++</option><option value="java">Java</option></select><textarea name="ordering_source">x = 1\nprint(x)</textarea></div><div data-ojp-code-completion><input name="completion_language_key" value="python"><textarea name="starter_code">{{OJ_BLANK:a}}</textarea><button type="button" data-ojp-add-blank>빈칸</button><div data-ojp-blank-list></div><input type="hidden" data-ojp-completion-schema name="code_completion_schema" value="{&quot;language_key&quot;:&quot;python&quot;,&quot;blanks&quot;:[{&quot;id&quot;:&quot;a&quot;,&quot;label&quot;:&quot;빈칸&quot;,&quot;kind&quot;:&quot;inline&quot;,&quot;max_bytes&quot;:10}]}"></div></form>';
  const browser = await chromium.launch({headless:true, channel:'chrome'});
  try {
    const page = await browser.newPage({viewport:{width:1280,height:900}});
    const failures = [];
    page.on('pageerror', error => failures.push(error.message));
    await page.route('**/*', async route => {
      const url = new URL(route.request().url());
      assert.equal(url.hostname, 'ordering.test');
      if (url.pathname.startsWith('/resources/')) {
        const file = path.resolve(root, '.' + url.pathname);
        assert(file.startsWith(root + path.sep));
        return route.fulfill({contentType:file.endsWith('.css') ? 'text/css' : 'text/javascript', body:fs.readFileSync(file)});
      }
      return route.fulfill({contentType:'text/html', body:'<!doctype html><html lang="ko"><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/resources/ui/css/oj-ui-system.css"><body class="ojp-app"><main class="ojp-shell">' + fixture.html + teacher + '</main><script src="/resources/ui/js/oj-ui.js" defer></script></body></html>'});
    });
    await page.goto('http://ordering.test/');
    await page.waitForSelector('[data-oj-code-ordering][data-mounted="true"]');
    const getOrder = () => page.evaluate(() => document.querySelector('[data-oj-code-ordering]').ojCodeOrdering.getOrder());
    const first = await getOrder();
    assert.deepEqual(first.slice().sort(), fixture.ids.slice().sort(), 'public shuffle preserves exactly the registered block IDs');
    assert.equal(await page.locator('input[name=source]').inputValue(), '');
    assert.equal(await page.locator('[data-oj-submission-form] textarea').count(), 0);
    assert.equal(await page.locator('[data-oj-ordering-submit]').isEnabled(), true);
    assert.equal(await page.evaluate(() => Boolean(window.unsafe)), false);
    assert.equal(await page.locator('#teacher [data-ojp-code-completion]').isVisible(), false);
    assert.equal(await page.locator('#teacher [name=starter_code]').isDisabled(), true);
    assert.equal(await page.locator('#teacher [name=ordering_source]').isEnabled(), true);
    const selectedLanguages = () => page.locator('#teacher input[name="enabled_language_ids[]"]:checked').evaluateAll(inputs => inputs.map(input => input.value));
    assert.deepEqual(await selectedLanguages(), ['6']);
    assert.equal(await page.locator('#teacher input[name="enabled_language_ids[]"]:disabled').count(), 4);
    await page.locator('#teacher [name=ordering_language_key]').selectOption('cpp');
    assert.deepEqual(await selectedLanguages(), ['1']);
    await page.locator('#teacher [value=code_completion]').check();
    assert.equal(await page.locator('#teacher [data-ojp-code-completion]').isVisible(), true);
    assert.equal(await page.locator('#teacher [name=ordering_source]').isDisabled(), true);
    assert.equal(await page.locator('#teacher [name=starter_code]').isEnabled(), true);
    assert.deepEqual(await selectedLanguages(), ['0', '6'], 'leaving ordering restores previous allowed languages');
    assert.equal(await page.locator('#teacher input[name="enabled_language_ids[]"]:disabled').count(), 0);
    await page.locator('#teacher [value=full_code]').check();
    assert.equal(await page.locator('#teacher [name=starter_code]').isEnabled(), true);
    assert.equal(await page.locator('#teacher [name=code_completion_schema]').isDisabled(), true);
    await page.locator('#teacher input[name="enabled_language_ids[]"][value="3"]').check();
    await page.locator('#teacher [value=code_ordering]').check();
    assert.deepEqual(await selectedLanguages(), ['1']);
    await page.locator('#teacher [value=full_code]').check();
    assert.deepEqual(await selectedLanguages(), ['0', '3', '6'], 'later edits are restored on subsequent mode switches');
    await page.locator('#teacher [value=code_ordering]').check();
    await page.locator('#teacher').evaluate(form => { form.hidden = true; });
    const codeBefore = await page.locator('[data-oj-ordering-block-id] code').allTextContents();
    await page.locator('[data-oj-ordering-move=down]').first().click();
    const second = await getOrder();
    assert.deepEqual(second, [first[1], first[0], ...first.slice(2)]);
    await page.reload();
    await page.waitForSelector('[data-oj-code-ordering][data-mounted="true"]');
    assert.deepEqual(await getOrder(), second, 'refresh restores exact draft order');
    await page.locator('[data-oj-ordering-block-id]').nth(1).focus();
    await page.keyboard.press('Alt+ArrowUp');
    assert.deepEqual(await getOrder(), first, 'keyboard reorders without editing text');
    const beforeDrag = await getOrder();
    await page.locator('[data-oj-ordering-block-id]').first().dragTo(page.locator('[data-oj-ordering-block-id]').nth(3));
    assert.notDeepEqual(await getOrder(), beforeDrag, 'drag changes order');
    const afterDrag = await getOrder();
    assert.equal(new Set(afterDrag).size, fixture.ids.length);
    const apiResult = await page.evaluate(ids => {
      const api = document.querySelector('[data-oj-code-ordering]').ojCodeOrdering;
      const before = api.getOrder();
      return {duplicate:api.setOrder(Array(ids.length).fill(ids[0])), unknown:api.setOrder([...ids.slice(1), 'unknown']), unchanged:JSON.stringify(before) === JSON.stringify(api.getOrder())};
    }, fixture.ids);
    assert.deepEqual(apiResult, {duplicate:false,unknown:false,unchanged:true});
    const submitted = await page.evaluate(() => {
      const form = document.querySelector('[data-oj-submission-form]');
      const event = new Event('submit', {cancelable:true}); form.dispatchEvent(event);
      const data = new FormData(form);
      return {prevented:event.defaultPrevented, ids:data.getAll('ordering_block_ids[]'), source:data.get('source'), context:data.get('class_id'), hash:data.get('template_hash'), nonce:data.get('nonce')};
    });
    assert.deepEqual(submitted.ids, afterDrag);
    assert.equal(submitted.prevented, false); assert.equal(submitted.source, '');
    assert.equal(submitted.context, '77'); assert.equal(submitted.hash, fixture.hash); assert.equal(submitted.nonce, 'fixture-token');
    const codeAfter = await page.locator('[data-oj-ordering-block-id] code').allTextContents();
    assert.deepEqual(codeAfter.slice().sort(), codeBefore.slice().sort(), 'code and indentation stay unchanged');
    await page.locator('[data-oj-ordering-list]').evaluate(list => list.scrollIntoView({block:'center'}));
    const measure = () => page.evaluate(() => {
      const list=document.querySelector('[data-oj-ordering-list]');
      const bounds=list.getBoundingClientRect();
      return {listHeight:bounds.height,top:bounds.top,bottom:bounds.bottom,viewportHeight:innerHeight,
        rows:[...list.children].map(block=>{const rect=block.getBoundingClientRect(),pre=block.querySelector('pre'),code=pre.getBoundingClientRect(),controls=block.querySelector('.ojp-code-ordering__controls').getBoundingClientRect();return {height:rect.height,codeTop:code.top-rect.top,controlsTop:controls.top-rect.top,margin:getComputedStyle(pre).margin,padding:getComputedStyle(pre).padding,terminalNewline:pre.textContent.endsWith('\n')};})};
    });
    const desktopMetrics=await measure();
    assert.equal(desktopMetrics.rows.length,5);
    desktopMetrics.rows.forEach(row=>{assert(row.height>=36&&row.height<=44,'single-line desktop block must be 36–44px');assert.equal(row.margin,'0px');assert.equal(row.padding,'0px');assert.equal(row.terminalNewline,false);assert(Math.abs(row.codeTop-row.controlsTop)<8,'code and controls share one row');});
    assert(desktopMetrics.listHeight<=236&&desktopMetrics.top>=0&&desktopMetrics.bottom<=desktopMetrics.viewportHeight,'all five rows must fit in one desktop viewport');
    const multiline=await page.evaluate(()=>{
      const sample=document.querySelector('[data-oj-ordering-block-id]');
      const root=document.createElement('section');root.className='ojp-code-ordering';const list=document.createElement('ol');list.className='ojp-code-ordering__list';list.setAttribute('data-oj-ordering-list','');root.appendChild(list);
      ['message = (\n    "one"\n    "two"\n)\n','print(message)\n'].forEach((text,index)=>{const block=sample.cloneNode(true);block.setAttribute('data-oj-ordering-block-id','multiline-'+index);block.querySelector('pre').removeAttribute('data-oj-ordering-display-normalized');block.querySelector('code').textContent=text;list.appendChild(block);});document.body.appendChild(root);window.OJPlatformCodeOrdering.mount(root);
      const result={height:list.children[0].getBoundingClientRect().height,text:list.children[0].querySelector('code').textContent,singleHeight:list.children[1].getBoundingClientRect().height};root.remove();return result;
    });
    assert(multiline.height>=80&&multiline.height<=100&&multiline.singleHeight<=44,'multiline blocks use natural content height');
    assert.equal(multiline.text,'message = (\n    "one"\n    "two"\n)','only the structural terminal LF is omitted in the display');
    await page.locator('[data-oj-submission-form]').screenshot({path:path.join(visualOutput, 'code-ordering-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const mobileOrder = await getOrder();
    await page.locator('[data-oj-ordering-move=down]').first().click();
    assert.notDeepEqual(await getOrder(), mobileOrder, 'touch-sized buttons work at mobile width');
    assert.equal(await page.locator('[data-oj-ordering-move=up]').first().isDisabled(), true);
    assert.equal(await page.locator('[data-oj-ordering-move=down]').last().isDisabled(), true);
    await page.locator('[data-oj-ordering-list]').evaluate(list=>list.scrollIntoView({block:'center'}));
    const mobileMetrics=await measure();mobileMetrics.rows.forEach(row=>assert(row.height>=40&&row.height<=44,'mobile block must remain one 40–44px row'));
    assert(mobileMetrics.listHeight<=236&&mobileMetrics.top>=0&&mobileMetrics.bottom<=mobileMetrics.viewportHeight,'five rows fit in one mobile viewport');
    const beforeTouch=await getOrder();
    const handle=await page.locator('[data-oj-ordering-handle]').first().boundingBox();
    const destination=await page.locator('[data-oj-ordering-block-id]').nth(3).boundingBox();
    const cdp=await page.context().newCDPSession(page);const x=handle.x+handle.width/2,y=handle.y+handle.height/2,targetY=destination.y+destination.height-5;
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y+10}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:targetY}]});
    assert.equal(await page.locator('.is-drop-before,.is-drop-after').count(),1,'touch drag shows its insertion target');
    await page.locator('[data-oj-submission-form]').screenshot({path:path.join(visualOutput,'code-ordering-touch-drop-mobile.png')});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await cdp.detach();
    assert.notDeepEqual(await getOrder(),beforeTouch,'touch handle moves a code block');
    assert.deepEqual((await getOrder()).slice().sort(),fixture.ids.slice().sort(),'touch dragging preserves all blocks exactly once');
    assert.equal(await page.locator('.is-drop-before,.is-drop-after,.is-dragging').count(),0,'drop markers clear after touch drag');
    await page.locator('[data-oj-submission-form]').screenshot({path:path.join(visualOutput, 'code-ordering-mobile.png')});
    fs.writeFileSync(path.join(visualOutput,'measurements.json'),JSON.stringify({desktop:desktopMetrics,mobile:mobileMetrics,multiline},null,2)+'\n','utf8');
    assert.equal(failures.length, 0, failures.join('\n'));
    console.log('Code ordering: 5 compact rows fit desktop/mobile, multiline height, mouse/touch drag with insertion markers, buttons/keyboard, draft restore and submission payload passed.');
    console.log('Screenshots: ' + visualOutput);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
