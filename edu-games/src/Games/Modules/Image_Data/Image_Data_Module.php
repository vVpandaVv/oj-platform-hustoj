    /**
     * @param array<int, array<string, mixed>> $samples
     * @return array<int, array<string, mixed>>
     */
    private static function curate_simple_samples(array $samples): array {
        $allowed_ids = array(
            'heart',
            'house',
            'tree',
            'flower',
            'smile',
            'rocket',
            'umbrella',
            'mountain',
            'sun',
            'moon',
            'star',
            'cloud',
            'rain',
            'balloon',
            'fish',
            'apple',
            'carrot',
            'pizza',
            'cup',
            'book',
            'pencil',
            'key',
            'lock',
            'clock',
            'gift',
            'flag',
            'candle',
            'music',
            'leaf',
            'chess',
            'rainbow',
            'letter-a',
            'number-5',
        );

        $allowed = array_fill_keys($allowed_ids, true);

        return array_values(array_filter(
            $samples,
            static function (array $sample) use ($allowed): bool {
                return isset($sample['id'], $allowed[$sample['id']]);
            }
        ));
    }

    /**
     * @param array<int, string> $data
     * @return array<string, mixed>
     */
    private static function sample(string $id, string $title, string $description, array $data): array {
        return array(
            'id' => $id,
            'title' => $title,
            'description' => $description,
            'data' => $data,
        );
    }
