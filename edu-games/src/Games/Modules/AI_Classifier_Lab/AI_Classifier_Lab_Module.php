    /**
     * @return array<string, mixed>
     */
    private static function rule(string $id, string $label, string $line_type, int|float $threshold, string $comparison = 'gte'): array {
        return array(
            'id' => $id,
            'label' => $label,
            'lineType' => $line_type,
            'threshold' => $threshold,
            'comparison' => $comparison,
        );
    }

    public static function predict(array $rule, array $point): string {
        $value = match ($rule['lineType']) {
            'horizontal' => $point['y'],
            'vertical' => $point['x'],
            'diagonal-neg' => $point['x'] + $point['y'],
            'diagonal-pos' => $point['y'] - $point['x'],
        };
        $matches = 'lte' === $rule['comparison'] ? $value <= $rule['threshold'] : $value >= $rule['threshold'];
        return $matches ? 'B' : 'A';
    }

