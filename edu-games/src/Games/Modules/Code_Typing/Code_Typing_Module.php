    /**
     * @return array<int, array<string, mixed>>
     */
    private static function reviewed_samples(): array {
        $file=__DIR__.'/expected-output.json';
        $outputs=is_file($file)?json_decode((string)file_get_contents($file),true):array();
        return array_map(static function(array $sample) use ($outputs): array {
            $sample['languageVersion']=$sample['language']==='python'?'Python 3.12':'C17';
            $sample['sourceKind']=$sample['mode']==='keyword'?'단어 목록':($sample['language']==='c'&&!str_contains($sample['content'],'main(')?'비실행 코드 조각':'완전 코드');
            $sample['concepts']=array($sample['description']);
            $sample['inputPolicy']='표준 입력 없음';
            $sample['outputPolicy']=$sample['mode']==='keyword'?'실행 대상 아님':'예제별 출력 · 타자 점수와 의미 이해는 별도 평가';
            $output=$outputs[$sample['id']]??null;
            if($output&&hash('sha256',$sample['content'])===$output['sha256']){$sample['expectedInput']=$output['stdin'];$sample['expectedOutput']=$output['stdout'];}
            return $sample;
        },self::samples());
    }

