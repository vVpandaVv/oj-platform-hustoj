"""Reproducible kNN predictions for each public survey subset; no runtime training."""
import json
import os
import subprocess
from pathlib import Path
os.environ.setdefault('LOKY_MAX_CPU_COUNT', '1')
import numpy as np
import sklearn
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import confusion_matrix

ROOT = Path(__file__).resolve().parents[2]
specs = json.loads(subprocess.check_output([os.environ.get('PHP_BINARY', 'D:/php/php.exe'), str(ROOT / 'scripts/edu-game/export-classifier-specs.php')], encoding='utf-8'))
bank = {'engine': 'scikit-learn', 'version': sklearn.__version__, 'cases': {}, 'solutions': {}}
for key, spec in specs.items():
    cases = {}
    candidates = []
    for mask in range(16):
        training = spec['training'] + [p for i, p in enumerate(spec['surveys']) if mask & (1 << i)]
        cases[mask] = {}
        for k in (1, 3, 5):
            model = KNeighborsClassifier(n_neighbors=k, algorithm='brute')
            model.fit([[p['x'], p['y']] for p in training], [p['label'] for p in training])
            result = {}
            for split, points in [('training', training), ('validation', spec['validation']), ('test', spec['test'])]:
                predicted = model.predict([[p['x'], p['y']] for p in points])
                matrix = confusion_matrix([p['label'] for p in points], predicted, labels=[0, 1])
                result[split] = {'accuracy': round(100 * float(np.trace(matrix)) / len(points), 2), 'matrix': matrix.tolist(), 'count': len(points)}
            result['surface'] = model.predict([[x + .5, y + .5] for x in range(10) for y in range(10)]).tolist()
            cases[mask][k] = result
            if min(result['validation']['accuracy'], result['test']['accuracy']) >= spec['threshold']:
                candidates.append((4 + (k != 3) + 2 * mask.bit_count(), -result['validation']['accuracy'], mask, k))
    bank['cases'][key] = cases
    if candidates:
        cost, _, mask, k = min(candidates)
        bank['solutions'][key] = {'mask': mask, 'k': k, 'cost': cost}
    print(f'{key}: 48 experiments; valid kNN policies={len(candidates)}', flush=True)
assert 'board-12' in bank['solutions'], 'The circular board must be solvable with kNN.'
encoded = json.dumps(bank, ensure_ascii=False, separators=(',', ':'))
(ROOT / 'src/Games/Modules/AI_Classifier_Lab/neighbor-experiments.php').write_text("<?php\ndeclare(strict_types=1);\n// Generated by build-neighbor-experiments.py; server only.\nreturn json_decode(<<<'NEIGHBORS'\n" + encoded + "\nNEIGHBORS, true, 512, JSON_THROW_ON_ERROR);\n", encoding='utf-8')
