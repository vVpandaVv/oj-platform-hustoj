"""Build every supported four-card deck with sklearn 1NN. No runtime dependency."""
import os
os.environ.setdefault("LOKY_MAX_CPU_COUNT", "1")
import itertools
import json
from pathlib import Path
import sklearn
from sklearn.neighbors import KNeighborsClassifier

ROOT = Path(__file__).resolve().parents[2]
bank = {"engine": "scikit-learn", "engineVersion": sklearn.__version__, "model": "1-nearest-neighbor", "boards": {}}
coordinates = [(1, 2), (2, 1), (2, 3), (3, 2), (7, 2), (8, 3), (2, 8), (8, 8)]
validation = [(1.2, 2.5), (2.5, 1.2), (2.5, 3.2), (3.5, 2.4), (6.8, 1.8), (7.5, 3.5), (1.8, 7.2), (2.5, 8.2), (7.2, 7.8), (8.5, 8.5), (6.5, 3.1), (3.1, 6.5)]
test = [(1.4, 2.8), (2.8, 1.4), (3.2, 3.1), (3.7, 1.8), (6.5, 2.4), (8.4, 2.5), (1.4, 8.1), (2.8, 7.5), (7.5, 8.4), (8.3, 7.2), (7.8, 1.4), (2.7, 6.8)]
for level in ("board-01", "board-02"):
    def label(x, y):
        return int(x > 5) if level == "board-01" else int((x > 5) != (y > 5))
    cards = [{"id": i, "x": x, "y": y, "truth": label(x, y), "label": 1-label(x,y) if i == 6 else label(x,y)} for i, (x, y) in enumerate(coordinates)]
    entry = {"cards": cards, "validation": [{"x": x, "y": y, "good": label(x,y)} for x,y in validation], "test": [{"x": x, "y": y, "good": label(x,y)} for x,y in test], "decks": {}}
    for subset in itertools.combinations(range(8), 4):
        mask = sum(1 << i for i in subset)
        for repaired in (0, 1):
            training = [cards[i] for i in subset]
            model = KNeighborsClassifier(n_neighbors=1, algorithm="brute", n_jobs=1)
            model.fit([[c["x"],c["y"]] for c in training], [c["truth"] if repaired and c["id"] == 6 else c["label"] for c in training])
            entry["decks"][f"{mask}:{repaired}"] = {
                "validation": model.predict(validation).tolist(),
                "test": model.predict(test).tolist()
            }
    bank["boards"][level] = entry
target = ROOT / "src/Games/Modules/AI_Model_Lab/deck-experiments.php"
encoded = json.dumps(bank, ensure_ascii=False, separators=(",", ":"))
target.write_text("<?php\ndeclare(strict_types=1);\n// Generated by build-deck-experiments.py; server-only finite deck predictions.\nreturn json_decode(<<<'DECKS'\n" + encoded + "\nDECKS, true, 512, JSON_THROW_ON_ERROR);\n", encoding="utf-8")
print(f"{len(bank['boards']) * 140} actual deck experiments; sklearn {sklearn.__version__}")

