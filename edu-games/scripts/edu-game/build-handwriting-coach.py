"""Exact 1-NN neighbor orders for arbitrary learner-selected images and labels."""
import json
import os
from itertools import combinations
from pathlib import Path

import numpy as np
from sklearn.datasets import load_digits
from sklearn.neighbors import KNeighborsClassifier
from sklearn.model_selection import train_test_split

os.environ.setdefault("LOKY_MAX_CPU_COUNT", "2")

digits = load_digits()
rng = np.random.default_rng(915)
# Split within each class so every three-digit combination has equal class counts.
candidates, validation, final = [], [], []
for n in range(10):
    ids = np.flatnonzero(digits.target == n)
    pool, test = train_test_split(ids, test_size=30, random_state=913)
    pool, valid = train_test_split(pool, test_size=4, random_state=914)
    candidates.extend(rng.choice(pool, 12, replace=False))
    validation.extend(valid)
    final.extend(test)
candidates, validation, final = map(np.array, (candidates, validation, final))
rng.shuffle(candidates)
rng.shuffle(validation)
rng.shuffle(final)

def sample(i):
    return {"sourceId": int(i), "pixels": digits.data[i].astype(int).tolist(), "label": str(digits.target[i])}

def rows(indices):
    result = []
    for i in indices:
        distance = np.sum((digits.data[candidates] - digits.data[i]) ** 2, axis=1)
        order = np.lexsort((np.arange(len(candidates)), distance)).tolist()
        result.append({**sample(i), "neighbors": order})
    return result

data = {"source": "scikit-learn load_digits / UCI Optical Recognition of Handwritten Digits", "model": "1-nearest-neighbor, squared Euclidean distance; ties by candidate index", "candidates": [sample(i) for i in candidates], "validation": rows(validation), "final": rows(final)}
data["attribution"] = {"creators": "E. Alpaydin and C. Kaynak (1998)", "doi": "https://doi.org/10.24432/C50P49", "license": "CC BY 4.0", "licenseUrl": "https://creativecommons.org/licenses/by/4.0/", "changes": "digits 0-9; balanced, disjoint candidate/validation/final splits; derived neighbor orders"}

# Check selected subsets and arbitrary relabeling, not only correct packaged labels.
checks = 0
for classes in combinations(range(10), 3):
    available = np.flatnonzero(np.isin(digits.target[candidates], classes))
    targets = [row for row in data["validation"] + data["final"] if int(row["label"]) in classes]
    for _ in range(3):
        selected = sorted(rng.choice(available, rng.integers(1, 10), replace=False).tolist())
        labels = rng.choice(classes, len(selected))
        model = KNeighborsClassifier(n_neighbors=1, algorithm="brute").fit(digits.data[candidates[selected]], labels)
        expected = model.predict(digits.data[[row["sourceId"] for row in targets]])
        label_map = dict(zip(selected, labels))
        actual = [label_map[next(n for n in row["neighbors"] if n in label_map)] for row in targets]
        assert np.array_equal(actual, expected)
        checks += len(actual)

target = Path(__file__).resolve().parents[2] / "src/Games/Modules/AI_Model_Lab/handwriting-data.php"
target.write_text("<?php\n// Generated by scripts/edu-game/build-handwriting-coach.py. Server-only evaluation data.\nreturn json_decode(<<<'JSON'\n" + json.dumps(data, separators=(",", ":")) + "\nJSON\n, true, 512, JSON_THROW_ON_ERROR);\n", encoding="utf-8")
print(f"{checks} exact sklearn prediction comparisons passed; {target}")
