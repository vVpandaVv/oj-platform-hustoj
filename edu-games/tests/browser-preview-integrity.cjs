const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({page,url,out,typingFixture}) => {
    let checks=0;
    const check=(ok,label)=>{assert(ok,label);checks++;};
    const teacher='/oj-console/addons/edu-games/typing-evaluations';
    await page.setViewportSize({width:1280,height:900});
    await page.goto(url+teacher);
    await page.locator('[data-action=new]').click();
    check(await page.locator('[data-context-index]').count()===2,'teacher can select both real fixture classes');
    await page.locator('[data-context-index="0"]').check();
    await page.locator('[data-context-index="1"]').check();
    await page.locator('[data-sample-id]').first().check();
    await page.locator('[name=title]').fill('전체 미리보기 학급 검정');
    await page.locator('[name=durationSeconds]').selectOption('60');
    await page.locator('[data-field=create-submit]').click();
    await page.locator('[data-action=change-status]').waitFor();
    await page.locator('[data-action=change-status]').click();
    await page.waitForFunction(()=>document.querySelector('[data-field=evaluation-status]').textContent.includes('응시 가능')||document.querySelector('[data-field=status-button]').textContent.includes('마감'));
    const link=await page.locator('[data-field=student-link]').getAttribute('href');
    check(link.includes('/oj-addons/edu-games/games/code-typing?evaluation=1'),'teacher shares a routable plugin URL');
    check(typingFixture({actor:1,path:'/typing/evaluations/1/results'}).data.summary.assigned===60,'two classes assign 60 students');
    await page.screenshot({path:path.join(out,'preview-integrity-teacher.png'),fullPage:true});

    await page.goto(url+'/?game=code-typing');
    check(await page.locator('[data-typing-assignments]').isHidden(),'classroom dashboard is collapsed on initial game entry');
    await page.locator('[data-typing-assignment-panel]>summary').click();
    await page.locator('[data-typing-assignment-card="1"]').waitFor();
    check(await page.locator('[data-code-typing]').evaluate(r=>!!r.__CodeTyping.verified),'all-games preview mounts the verified module');
    const scripts=await page.evaluate(()=>[...document.scripts].map(s=>new URL(s.src,location.href).pathname));
    check(scripts.some(s=>s.endsWith('/typing/entry.js'))&&scripts.some(s=>s.endsWith('/typing/verified.js')),'registered typing dependencies are both present');
    check(!(await page.locator('[data-typing-assignments]').innerText()).includes('평가 조회 중'),'student assignment loading completes');
    check(await page.locator('[data-typing-evaluation="1"]').isVisible(),'participation is a visible action');
    await page.screenshot({path:path.join(out,'preview-integrity-student.png'),fullPage:true});
    await page.goto(url+'/oj-addons/edu-games/games');
    await page.locator('[data-typing-assignment-card="1"]').waitFor();
    check(await page.locator('[data-typing-entry-hub] .ete-student-action').isVisible(),'student hub restores the evaluation entry');
    await page.locator('[data-typing-entry-hub] .ete-student-action').click();
    await page.waitForFunction(()=>document.querySelector('[data-code-typing]')?.__CodeTyping.verified?.evaluation?.id===1);
    await page.waitForSelector('[data-code-typing][data-typing-evaluation-selected]');
    check(await page.locator('.oj-typing-controls').isHidden(),'selected class examination hides personal-practice settings');
    check(await page.locator('[data-code-typing]').evaluate(r=>r.__CodeTyping.state.status==='idle'),'viewing an evaluation does not start the timer');
    check(typingFixture({actor:7,path:'/typing/assigned'}).data.evaluations[0].attempts.length===0,'viewing an evaluation does not consume an attempt');
    const first=await page.locator('[data-code-typing]').evaluate(r=>r.__CodeTyping.currentSample().content[0]);
    await page.locator('[data-field=input]').pressSequentially(first);
    await page.waitForFunction(()=>!!document.querySelector('[data-code-typing]').__CodeTyping.verified.remote);
    check(await page.locator('[data-typing-assignment-panel]').isHidden(),'classroom dashboard does not occupy the running examination');
    await page.locator('[data-code-typing]').evaluate(r=>r.__CodeTyping.verified.flush());
    const token=await page.locator('[data-code-typing]').evaluate(r=>r.__CodeTyping.verified.remote.token);
    let report=typingFixture({actor:1,path:'/typing/evaluations/1/results'}).data;
    check(report.summary.running===1&&report.summary.absent===59,'teacher sees the student running in the shared preview database');
    typingFixture({actor:7,action:'expire',token,settle:true});
    await page.locator('[data-code-typing]').evaluate(r=>{r.__CodeTyping.verified.deadline=performance.now()-1;return r.__CodeTyping.verified.finish();});
    await page.locator('[data-student-final-result]').waitFor();
    check(await page.locator('[data-student-final-result] [data-student-cpm]').isVisible(),'student sees confirmed effective CPM');
    check(await page.locator('[data-student-final-result] [data-student-accuracy]').isVisible(),'student sees confirmed input accuracy');
    report=typingFixture({actor:1,path:'/typing/evaluations/1/results'}).data;
    check(report.summary.completed===1&&report.summary.absent===59,'teacher retains the completed student result');
    await page.goto(url+teacher);await page.locator('[data-action=results]').first().click();
    await page.locator('.ete-comparison-table').waitFor();
    check(await page.locator('[data-participant-row][data-result-state=finished]').count()===1,'teacher result screen shows the completed participant');

    await page.route('**/assets/typing/verified.js',route=>route.abort());
    await page.goto(url+'/?game=code-typing');
    await page.waitForSelector('[data-typing-assessment=unavailable]');
    check((await page.locator('[data-typing-assignments]').innerText()).includes('모듈을 불러오지 못했습니다'),'missing dependency is not an endless loading state');
    check(await page.getByRole('button',{name:'다시 불러오기',exact:true}).isVisible(),'failed assessment loading offers recovery');
    await page.unroute('**/assets/typing/verified.js');
    await page.goto(url+'/?game=code-typing');
    await page.locator('[data-typing-assignment-panel]>summary').click();
    await page.locator('[data-typing-assignment-card="1"]').waitFor();
    await page.locator('[data-code-typing]').evaluate(r=>r.__GameViewport.open());
    check(!await page.locator('[data-typing-assignments]').isVisible(),'personal focused practice does not push the code board below evaluation cards');
    await page.locator('[data-code-typing]').evaluate(r=>r.__GameViewport.close());
    check(await page.locator('[data-typing-assignment-card="1"]').isVisible(),'leaving focused practice restores class participation');
    console.log(checks+' all-games preview assessment integrity checks passed');
};
