<?php
declare(strict_types=1);

/**
 * Runs only when the plugin is removed via "삭제" in the Plugins screen —
 * never on deactivate/reactivate. WordPress includes this file standalone
 * (the main focus-tracker.php bootstrap, its autoloader, and every
 * FOCUS_TRACKER_* constant are NOT loaded), so table/option names are
 * hardcoded here rather than reused from Installer.
 */

if (! defined('WP_UNINSTALL_PLUGIN')) {
    exit;
}

global $wpdb;

$events_table = $wpdb->prefix . 'focus_tracker_events';
$scores_table = $wpdb->prefix . 'focus_tracker_scores';
$participations_table = $wpdb->prefix . 'focus_tracker_participations';
$activities_table = $wpdb->prefix . 'focus_tracker_activities';
$links_table = $wpdb->prefix . 'focus_tracker_activity_links';
$checks_table = $wpdb->prefix . 'focus_tracker_checks';
$check_states_table = $wpdb->prefix . 'focus_tracker_check_states';
$statistics_table = $wpdb->prefix . 'focus_tracker_daily_statistics';

// Drop in dependency order: events/scores reference participations, which
// reference activities.
$wpdb->query("DROP TABLE IF EXISTS {$events_table}");
$wpdb->query("DROP TABLE IF EXISTS {$scores_table}");
$wpdb->query("DROP TABLE IF EXISTS {$links_table}");
$wpdb->query("DROP TABLE IF EXISTS {$checks_table}");
$wpdb->query("DROP TABLE IF EXISTS {$check_states_table}");
$wpdb->query("DROP TABLE IF EXISTS {$statistics_table}");
$wpdb->query("DROP TABLE IF EXISTS {$participations_table}");
$wpdb->query("DROP TABLE IF EXISTS {$activities_table}");

// Remove only the learner role grant introduced by this plugin. Preserve a
// capability that existed before the one-time default and all individual caps.
$student_defaults = get_option('focus_tracker_student_participation_defaults', array());
if (is_array($student_defaults) && ($student_defaults['schemaVersion'] ?? null) === 1
    && ($student_defaults['owned'] ?? false) === true && function_exists('get_role')) {
    $student_role = get_role('subscriber');
    // The standalone uninstall entry cannot load the Addon API mapper. This is
    // the stored WordPress key generated by AddonCapabilityKeyV1::wordpress().
    $participate_key = 'oj_addon_focus_tracker_participate';
    if (is_object($student_role) && ($student_role->capabilities[$participate_key] ?? null) === true
        && method_exists($student_role, 'remove_cap')) { $student_role->remove_cap($participate_key); }
}
delete_option('focus_tracker_student_participation_defaults');

delete_option('focus_tracker_db_version');
delete_option('focus_tracker_settings');
delete_option('focus_tracker_statistics_coverage_since');
delete_option('focus_tracker_schema_health');
delete_option('focus_tracker_schema_maintenance_lock');
delete_option('focus_tracker_schema_retry');
delete_option('focus_tracker_audit_log');
delete_option('focus_tracker_cleanup_lock');
delete_option('focus_tracker_cleanup_progress');
delete_option('focus_tracker_cleanup_status');
wp_clear_scheduled_hook('focus_tracker_cleanup_continue');
wp_clear_scheduled_hook('focus_tracker_cleanup');
$wpdb->query($wpdb->prepare("DELETE FROM {$wpdb->options} WHERE option_name LIKE %s ESCAPE '!' OR option_name LIKE %s ESCAPE '!'", 'focus!_tracker!_limit!_%', 'focus!_tracker!_diagnostic!_%'));
$wpdb->query($wpdb->prepare("DELETE FROM {$wpdb->options} WHERE option_name LIKE %s ESCAPE '!'", 'focus!_tracker!_privacy!_%'));
