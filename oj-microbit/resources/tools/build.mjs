import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const result = await build({
  entryPoints: [resolve(here, 'usb-entry.js')],
  outfile: resolve(here, '../vendor/microbit-usb.js'),
  bundle: true, format: 'iife', globalName: 'OJMicrobitUSB',
  platform: 'browser', target: ['chrome109', 'edge109'], minify: true,
  legalComments: 'linked', metafile: true,
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const normalized = input.replaceAll('\\', '/');
  const match = normalized.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
const chunks = ['OJ Microbit USB browser bundle — third-party notices\n\nGenerated by npm run build from the pinned package-lock.json.\n'];
for (const name of [...packages].sort()) {
  const folder = resolve(here, 'node_modules', name);
  const pkg = JSON.parse(await readFile(resolve(folder, 'package.json'), 'utf8'));
  let license;
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENSE.MD']) {
    try { license = await readFile(resolve(folder, file), 'utf8'); break; } catch {}
  }
  if (!license) throw new Error('Missing license for bundled dependency ' + name);
  chunks.push('\n' + name + '@' + pkg.version + '\n' + '='.repeat(60) + '\n' + license.trim() + '\n');
}
await writeFile(resolve(here, '../vendor/THIRD_PARTY_NOTICES.txt'), chunks.join('\n'), 'utf8');
