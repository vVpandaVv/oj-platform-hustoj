'use strict';

const fs = require('node:fs');
const path = require('node:path');

const PREFIX = 'ojrt1.';
const KEYS = ['REALTIME_SECRET', 'ALLOWED_ORIGINS', 'PORT', 'HOST', 'WS_PATH'];

function decode(code) {
    const raw = String(code || '').trim();
    if (!raw.startsWith(PREFIX)) throw new Error('Copy the setup command again from Teaching Tools settings.');
    let data;
    try {
        data = JSON.parse(Buffer.from(raw.slice(PREFIX.length), 'base64url').toString('utf8'));
    } catch {
        throw new Error('The setup code is incomplete or invalid.');
    }
    if (!data || data.v !== 1 || !data.env || typeof data.env !== 'object') throw new Error('Unknown setup code.');

    const env = {};
    for (const key of KEYS) {
        const value = String(data.env[key] == null ? '' : data.env[key]);
        if (/\r|\n/.test(value)) throw new Error(`${key} is invalid.`);
        env[key] = value;
    }
    if (env.REALTIME_SECRET.length < 32) throw new Error('REALTIME_SECRET is too short.');
    if (!/^https?:\/\//.test(env.ALLOWED_ORIGINS)) throw new Error('ALLOWED_ORIGINS is invalid.');
    if (!/^\d{2,5}$/.test(env.PORT) || Number(env.PORT) > 65535) throw new Error('PORT is invalid.');
    if (!/^\/[A-Za-z0-9/_-]+$/.test(env.WS_PATH)) throw new Error('WS_PATH is invalid.');
    return env;
}

function render(env) {
    return '# OJ Realtime Hub - generated by src/setup.js\n'
        + KEYS.map((key) => `${key}=${env[key]}`).join('\n') + '\n';
}

function write(env, directory) {
    const file = path.join(directory, '.env');
    const backup = fs.existsSync(file) ? file + '.bak' : '';
    if (backup) fs.copyFileSync(file, backup);
    fs.writeFileSync(file, render(env), { mode: 0o640 });
    return { file, backup };
}

if (require.main === module) {
    try {
        if (process.argv.length > 2) {
            throw new Error('Pass the setup code through standard input, not a command-line argument.');
        }
        const env = decode(fs.readFileSync(0, 'utf8'));
        const result = write(env, path.join(__dirname, '..'));
        console.log('Configuration written: ' + result.file);
        if (result.backup) console.log('Previous configuration saved: ' + result.backup);
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }
}

module.exports = { decode, render, write, KEYS };
