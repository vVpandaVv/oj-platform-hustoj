<?php
declare(strict_types=1);

namespace OjCodeArena\Support;

/**
 * Builds the game server's .env from the WordPress settings, and the
 * one-line setup code read by game-server/src/setup.js (keep the two in
 * step: "oca1." + base64url(json {v:1, env:{...}})).
 */
final class Server_Env {
    public const CODE_PREFIX = 'oca1.';
    public const KEYS = array('ARENA_SECRET', 'WP_API', 'ALLOWED_ORIGINS', 'PORT', 'HOST', 'WS_PATH');
    private const DEFAULT_PORT = 3210;

    /**
     * @param string $public_url browser address (ws/wss)
     * @param string $api_url    server-to-server address as entered ('' = derived from public)
     * @param string $rest_base  e.g. https://oj.example.com/wp-json/oj-code-arena/v1
     * @param string $home       site home URL (origin allowed to open sockets)
     * @return array<string,string>
     */
    public static function build(string $secret, string $public_url, string $api_url, string $rest_base, string $home): array {
        $public = self::parse($public_url);
        $api = self::parse($api_url);

        if (null !== $api && $api['port']) {
            // WordPress talks to the server directly on this port.
            $port = $api['port'];
            $host = self::loopback($api['host']) ? '127.0.0.1' : '0.0.0.0';
        } elseif (null === $api && null !== $public && $public['port']) {
            // Browsers reach the server directly (no proxy).
            $port = $public['port'];
            $host = '0.0.0.0';
        } else {
            // Behind the common hub's reverse proxy (127.0.0.1:3210).
            $port = self::DEFAULT_PORT;
            $host = '127.0.0.1';
        }

        $path = $public['path'] ?? ($api['path'] ?? '');
        $path = '' === $path || '/' === $path ? '/arena' : '/' . trim($path, '/');

        return array(
            'ARENA_SECRET' => $secret,
            'WP_API' => rtrim($rest_base, '/'),
            'ALLOWED_ORIGINS' => self::origin($home),
            'PORT' => (string) $port,
            'HOST' => $host,
            'WS_PATH' => $path,
        );
    }

    /** @param array<string,string> $env */
    public static function text(array $env): string {
        $out = "# OJ Code Arena game server — generated by WordPress (교사 메뉴 › 코드 아레나 › 설정)\n";
        foreach ($env as $k => $v) {
            $out .= $k . '=' . $v . "\n";
        }
        return $out;
    }

    /** @param array<string,string> $env */
    public static function setup_code(array $env): string {
        $json = (string) json_encode(array('v' => 1, 'env' => $env), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        return self::CODE_PREFIX . rtrim(strtr(base64_encode($json), '+/', '-_'), '=');
    }

    /** @param array<string,string> $env */
    public static function install_code(array $env): string {
        $json = (string) json_encode(
            array('v' => 1, 'app' => 'oj-code-arena', 'env' => $env),
            JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
        );

        return 'ojhub1.' . rtrim(strtr(base64_encode($json), '+/', '-_'), '=');
    }

    /** The automatic installer supports the site's own nginx proxy only. */
    public static function install_command(string $public_url, string $api_url, string $home, array $env, string $plugin_path): ?string {
        $public = parse_url($public_url);
        $site = parse_url($home);
        if (! is_array($public) || ! is_array($site) || empty($public['host']) || empty($site['host'])) {
            return null;
        }
        $secure = 'https' === ($site['scheme'] ?? '');
        $port = $secure ? 443 : 80;
        if (($public['scheme'] ?? '') !== ($secure ? 'wss' : 'ws')
            || strtolower($public['host']) !== strtolower($site['host'])
            || ($public['port'] ?? $port) !== ($site['port'] ?? $port)
            || isset($public['user']) || isset($public['pass']) || isset($public['query']) || isset($public['fragment'])
            || '127.0.0.1' !== ($env['HOST'] ?? '') || '3210' !== ($env['PORT'] ?? '')
            || ! preg_match('#^/[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*$#D', $env['WS_PATH'] ?? '')) {
            return null;
        }
        if ('' !== $api_url) {
            $api = parse_url($api_url);
            if (! is_array($api) || 'http' !== ($api['scheme'] ?? '') || '127.0.0.1' !== ($api['host'] ?? '')
                || ($api['port'] ?? 80) !== (int) $env['PORT'] || rtrim($api['path'] ?? '', '/') !== $env['WS_PATH']
                || isset($api['user']) || isset($api['pass']) || isset($api['query']) || isset($api['fragment'])) {
                return null;
            }
        }
        // POSIX quoting is deliberate: this command runs on Ubuntu/Debian, even if generated on Windows.
        $quote = static fn (string $value): string => "'" . str_replace("'", "'\"'\"'", $value) . "'";
        return 'sudo bash ' . $quote(rtrim($plugin_path, '/\\') . '/game-server/install.sh');
    }

    /** @return array{host: string, port: int, path: string}|null */
    private static function parse(string $url): ?array {
        $url = trim($url);
        if ('' === $url) {
            return null;
        }
        $parts = parse_url($url);
        if (! is_array($parts) || empty($parts['host'])) {
            return null;
        }
        return array(
            'host' => strtolower((string) $parts['host']),
            'port' => isset($parts['port']) ? (int) $parts['port'] : 0,
            'path' => (string) ($parts['path'] ?? ''),
        );
    }

    private static function loopback(string $host): bool {
        return in_array(trim($host, '[]'), array('127.0.0.1', 'localhost', '::1'), true);
    }

    private static function origin(string $home): string {
        $p = parse_url($home);
        if (! is_array($p) || empty($p['host'])) {
            return '';
        }
        return ($p['scheme'] ?? 'https') . '://' . $p['host'] . (isset($p['port']) ? ':' . $p['port'] : '');
    }
}
